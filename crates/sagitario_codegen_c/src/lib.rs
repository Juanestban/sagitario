//! C11 code generation from SIR (docs/architecture.md#c-code-generation). The output is strict,
//! portable C11 that includes `sagitario_runtime.h`. Integer arithmetic, negation and
//! float-to-integer casts go through runtime helpers so the generated C has no undefined
//! behavior; the helpers receive `__FILE__`/`__LINE__`, which `#line` maps back to the source.

use sagitario_ast::{BinaryOp, UnaryOp};
use sagitario_resolve::{Builtin, FnId};
use sagitario_sir::{Callee, Const, Function, Local, Operand, Program, Rvalue, Stmt, TemplatePiece};
use sagitario_types::{FloatTy, IntTy, Type};

pub const RUNTIME_HEADER: &str = "sagitario_runtime.h";

pub fn generate(program: &Program) -> String {
  let mut generator = Generator { out: String::new(), indent: 0, path: c_string_literal(program.source_path.as_bytes()) };

  generator.out.push_str("/* Generated by sag. Do not edit. */\n");
  generator.out.push_str(&format!("#include \"{RUNTIME_HEADER}\"\n\n"));

  for (index, function) in program.functions.iter().enumerate() {
    generator.out.push_str(&format!("static {};\n", signature(FnId(index as u32), function)));
  }

  generator.out.push('\n');

  for (index, function) in program.functions.iter().enumerate() {
    generator.function(FnId(index as u32), function);
  }

  generator.out.push_str("int main(int argc, char **argv) {\n");
  generator.out.push_str("  sag_rt_init(argc, argv);\n");
  generator.out.push_str(&format!("  {}();\n", fn_name(program.entry)));
  generator.out.push_str("  return sag_rt_finish();\n");
  generator.out.push_str("}\n");
  generator.out
}

struct Generator {
  out: String,
  indent: usize,
  /// The source path as a C string literal, for `#line`.
  path: String,
}

impl Generator {
  fn line(&mut self, text: &str) {
    for _ in 0..self.indent {
      self.out.push_str("  ");
    }

    self.out.push_str(text);
    self.out.push('\n');
  }

  fn function(&mut self, id: FnId, function: &Function) {
    self.out.push_str(&format!("static {} {{\n", signature(id, function)));
    self.indent = 1;

    for (index, ty) in function.locals.iter().enumerate().skip(function.param_count) {
      let init = if *ty == Type::String { "{0}" } else { "0" };

      self.line(&format!("{} {} = {init};", value_c_type(ty), local(Local(index as u32))));
    }

    self.stmts(&function.body);
    self.indent = 0;
    self.out.push_str("}\n\n");
  }

  fn stmts(&mut self, stmts: &[Stmt]) {
    for stmt in stmts {
      self.stmt(stmt);
    }
  }

  fn block(&mut self, header: &str, body: &[Stmt]) {
    self.line(&format!("{header} {{"));
    self.indent += 1;
    self.stmts(body);
    self.indent -= 1;
    self.line("}");
  }

  fn stmt(&mut self, stmt: &Stmt) {
    match stmt {
      // `#line` must start at column 0 to stay readable; C ignores the indentation anyway.
      Stmt::Line(line) => self.out.push_str(&format!("#line {line} {}\n", self.path)),
      Stmt::Assign { dest, value: Rvalue::Template(pieces) } => self.template(*dest, pieces),
      Stmt::Assign { dest, value } => {
        let value = rvalue(value);

        self.line(&format!("{} = {value};", local(*dest)));
      }
      Stmt::Eval(value) => {
        let value = rvalue(value);

        self.line(&format!("{value};"));
      }
      Stmt::Retain(value) => self.line(&format!("sag_string_retain({});", operand(value))),
      Stmt::Release(target) => self.line(&format!("sag_string_release({});", local(*target))),
      Stmt::Reset(target) => self.line(&format!("{} = sag_string_empty();", local(*target))),
      Stmt::If { cond, then_body, else_body } => {
        self.block(&format!("if ({})", operand(cond)), then_body);

        if !else_body.is_empty() {
          self.block("else", else_body);
        }
      }
      Stmt::Loop { body } => self.block("for (;;)", body),
      Stmt::ForRange { var, ty, start, end, inclusive, body } => {
        let c_ty = int_c_type(*ty);
        let counter = format!("sag_i{}", var.0);
        let (start, end) = (operand(start), operand(end));
        // A `continue` jumps to the increment, which must never step past `end` (it may be the
        // type's maximum), so the closed form tracks completion in a separate flag.
        let header = if *inclusive {
          let done = format!("sag_done{}", var.0);

          format!(
            "for ({c_ty} {counter} = {start}, {done} = ({c_ty})({start} > {end}); {done} == 0; \
             {done} = ({c_ty})({counter} == {end}), {counter} = {done} ? {counter} : ({c_ty})({counter} + 1))"
          )
        } else {
          format!("for ({c_ty} {counter} = {start}; {counter} < {end}; {counter} = ({c_ty})({counter} + 1))")
        };

        self.line(&format!("{header} {{"));
        self.indent += 1;
        self.line(&format!("{} = {counter};", local(*var)));
        self.stmts(body);
        self.indent -= 1;
        self.line("}");
      }
      Stmt::Break => self.line("break;"),
      Stmt::Continue => self.line("continue;"),
      Stmt::Return(None) => self.line("return;"),
      Stmt::Return(Some(value)) => self.line(&format!("return {};", operand(value))),
    }
  }

  fn template(&mut self, dest: Local, pieces: &[TemplatePiece]) {
    self.line("{");
    self.indent += 1;
    self.line("sag_sb sag_builder;");
    self.line("sag_sb_init(&sag_builder);");

    for piece in pieces {
      let push = match piece {
        TemplatePiece::Text(text) => {
          format!("sag_sb_push_bytes(&sag_builder, {}, {})", c_string_literal(text.as_bytes()), text.len())
        }
        TemplatePiece::Value(ty, value) => {
          let value = operand(value);

          match ty {
            Type::Int(int) if int.is_signed() => format!("sag_sb_push_i64(&sag_builder, (int64_t)({value}))"),
            Type::Int(_) => format!("sag_sb_push_u64(&sag_builder, (uint64_t)({value}))"),
            Type::Float(FloatTy::F32) => format!("sag_sb_push_f32(&sag_builder, {value})"),
            Type::Float(FloatTy::F64) => format!("sag_sb_push_f64(&sag_builder, {value})"),
            Type::Bool => format!("sag_sb_push_bool(&sag_builder, {value})"),
            Type::Char => format!("sag_sb_push_char(&sag_builder, {value})"),
            Type::String => format!("sag_sb_push_str(&sag_builder, {value})"),
            // Diverging or erroneous parts never reach code generation.
            Type::Unit | Type::Never | Type::Error => continue,
          }
        }
      };

      self.line(&format!("{push};"));
    }

    self.line(&format!("{} = sag_sb_finish(&sag_builder);", local(dest)));
    self.indent -= 1;
    self.line("}");
  }
}

fn signature(id: FnId, function: &Function) -> String {
  let params: Vec<String> = function
    .locals
    .iter()
    .take(function.param_count)
    .enumerate()
    .map(|(index, ty)| format!("{} {}", value_c_type(ty), local(Local(index as u32))))
    .collect();
  let params = if params.is_empty() { "void".to_string() } else { params.join(", ") };
  let ret = if matches!(function.ret, Type::Unit | Type::Never) { "void" } else { value_c_type(&function.ret) };

  format!("{ret} {}({params})", fn_name(id))
}

/// Functions are named by id, so any Sagitario identifier (including Unicode) is safe in C.
fn fn_name(id: FnId) -> String {
  format!("sag_fn_{}", id.0)
}

fn local(local: Local) -> String {
  format!("l{}", local.0)
}

/// The C type of a stored value. `()` has no data but is stored as a byte so it can be a
/// parameter or local.
fn value_c_type(ty: &Type) -> &'static str {
  match ty {
    Type::Unit | Type::Never | Type::Error => "uint8_t",
    Type::Bool => "bool",
    Type::Char => "uint32_t",
    Type::Int(int) => int_c_type(*int),
    Type::Float(FloatTy::F32) => "float",
    Type::Float(FloatTy::F64) => "double",
    Type::String => "sag_string",
  }
}

fn int_c_type(int: IntTy) -> &'static str {
  match int {
    IntTy::I8 => "int8_t",
    IntTy::I16 => "int16_t",
    IntTy::I32 => "int32_t",
    IntTy::I64 => "int64_t",
    IntTy::Isize => "intptr_t",
    IntTy::U8 => "uint8_t",
    IntTy::U16 => "uint16_t",
    IntTy::U32 => "uint32_t",
    IntTy::U64 => "uint64_t",
    IntTy::Usize => "size_t",
  }
}

fn rvalue(value: &Rvalue) -> String {
  match value {
    Rvalue::Use(value) => operand(value),
    Rvalue::Unary { op: UnaryOp::Not, operand: value, .. } => format!("(!{})", operand(value)),
    Rvalue::Unary { op: UnaryOp::Neg, ty: Type::Int(int), operand: value } => {
      format!("sag_neg_{}_at({}, __FILE__, __LINE__)", int.name(), operand(value))
    }
    Rvalue::Unary { op: UnaryOp::Neg, operand: value, .. } => format!("(-{})", operand(value)),
    Rvalue::Binary { op, ty, lhs, rhs } => binary(*op, ty, &operand(lhs), &operand(rhs)),
    Rvalue::Cast { from, to, operand: value } => cast(from, to, &operand(value)),
    Rvalue::Call { callee, args } => {
      let args: Vec<String> = args.iter().map(operand).collect();

      format!("{}({})", callee_name(*callee), args.join(", "))
    }
    // Templates are emitted as statements by `Generator::template`.
    Rvalue::Template(_) => "sag_string_empty()".to_string(),
  }
}

fn binary(op: BinaryOp, ty: &Type, lhs: &str, rhs: &str) -> String {
  let helper = match op {
    BinaryOp::Add => "add",
    BinaryOp::Sub => "sub",
    BinaryOp::Mul => "mul",
    BinaryOp::Div => "div",
    BinaryOp::Rem => "rem",
    // Comparisons are defined for every operand value; `&&`/`||` never reach here.
    _ => return format!("({lhs} {} {rhs})", op.symbol()),
  };

  match ty {
    Type::Int(int) => format!("sag_{helper}_{}_at({lhs}, {rhs}, __FILE__, __LINE__)", int.name()),
    Type::Float(FloatTy::F32) if op == BinaryOp::Rem => format!("fmodf({lhs}, {rhs})"),
    Type::Float(FloatTy::F64) if op == BinaryOp::Rem => format!("fmod({lhs}, {rhs})"),
    _ => format!("({lhs} {} {rhs})", op.symbol()),
  }
}

/// `as` conversions (docs/spec/02-types.md#conversions).
fn cast(from: &Type, to: &Type, value: &str) -> String {
  match (from, to) {
    (from, to) if from == to => value.to_string(),
    (Type::Float(_), Type::Int(int)) => format!("sag_f2i_{}((double)({value}))", int.name()),
    (Type::Float(FloatTy::F64), Type::Float(FloatTy::F32)) => format!("sag_f64_to_f32({value})"),
    // Integer narrowing keeps the low bits (two's complement on every supported target);
    // widening, int-to-float rounding and bool/char conversions are exact C conversions.
    _ => format!("(({}){value})", value_c_type(to)),
  }
}

fn callee_name(callee: Callee) -> String {
  match callee {
    Callee::Fn(id) => fn_name(id),
    Callee::Builtin(Builtin::Print) => "sag_print".to_string(),
    Callee::Builtin(Builtin::Println) => "sag_println".to_string(),
    Callee::Builtin(Builtin::Eprintln) => "sag_eprintln".to_string(),
  }
}

fn operand(operand: &Operand) -> String {
  match operand {
    Operand::Local(target) => local(*target),
    Operand::Const(Const::Unit) => "0".to_string(),
    Operand::Const(Const::Bool(value)) => value.to_string(),
    Operand::Const(Const::Char(value)) => format!("((uint32_t)0x{:X}u)", u32::from(*value)),
    Operand::Const(Const::Int { value, negative: false, ty }) => format!("(({}){value}ull)", int_c_type(*ty)),
    // `-(v - 1) - 1` avoids writing the positive magnitude of the minimum, which overflows.
    Operand::Const(Const::Int { value, negative: true, ty }) => match value.checked_sub(1) {
      Some(magnitude) => format!("(({})(-(int64_t){magnitude}ll - 1))", int_c_type(*ty)),
      None => format!("(({})0)", int_c_type(*ty)),
    },
    Operand::Const(Const::Float(text, float)) => {
      let text = if text.contains(['.', 'e']) { text.clone() } else { format!("{text}.0") };

      match float {
        FloatTy::F32 => format!("{text}f"),
        FloatTy::F64 => text,
      }
    }
    Operand::Const(Const::Str(value)) => {
      format!("sag_string_from_static({}, {})", c_string_literal(value.as_bytes()), value.len())
    }
  }
}

/// A C string literal holding exactly `bytes`. Anything outside printable ASCII becomes a
/// three-digit octal escape, which cannot merge with the following character. `?` is escaped to
/// avoid trigraphs.
fn c_string_literal(bytes: &[u8]) -> String {
  let mut out = String::from("\"");

  for &byte in bytes {
    match byte {
      b'"' => out.push_str("\\\""),
      b'\\' => out.push_str("\\\\"),
      b'?' => out.push_str("\\?"),
      b' '..=b'~' => out.push(char::from(byte)),
      _ => out.push_str(&format!("\\{byte:03o}")),
    }
  }

  out.push('"');
  out
}

#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn escapes_c_string_literals() {
    assert_eq!(c_string_literal(b"a\"b\\c?"), r#""a\"b\\c\?""#);
    assert_eq!(c_string_literal("ñ\n1".as_bytes()), r#""\303\261\0121""#);
  }

  #[test]
  fn formats_constants() {
    let int = |value, negative, ty| operand(&Operand::Const(Const::Int { value, negative, ty }));

    assert_eq!(int(255, false, IntTy::U8), "((uint8_t)255ull)");
    assert_eq!(int(5, true, IntTy::I32), "((int32_t)(-(int64_t)4ll - 1))");
    assert_eq!(int(9_223_372_036_854_775_808, true, IntTy::I64), "((int64_t)(-(int64_t)9223372036854775807ll - 1))");
    assert_eq!(operand(&Operand::Const(Const::Float("7".to_string(), FloatTy::F32))), "7.0f");
    assert_eq!(operand(&Operand::Const(Const::Float("-1e10".to_string(), FloatTy::F64))), "-1e10");
    assert_eq!(operand(&Operand::Const(Const::Char('A'))), "((uint32_t)0x41u)");
    assert_eq!(operand(&Operand::Const(Const::Str("hi".to_string()))), "sag_string_from_static(\"hi\", 2)");
  }

  #[test]
  fn uses_runtime_helpers_where_c_has_undefined_behavior() {
    assert_eq!(binary(BinaryOp::Add, &Type::Int(IntTy::I32), "a", "b"), "sag_add_i32_at(a, b, __FILE__, __LINE__)");
    assert_eq!(binary(BinaryOp::Lt, &Type::Int(IntTy::I32), "a", "b"), "(a < b)");
    assert_eq!(binary(BinaryOp::Rem, &Type::Float(FloatTy::F64), "a", "b"), "fmod(a, b)");
    assert_eq!(cast(&Type::Float(FloatTy::F64), &Type::Int(IntTy::U8), "x"), "sag_f2i_u8((double)(x))");
    assert_eq!(cast(&Type::Int(IntTy::I32), &Type::Int(IntTy::U8), "x"), "((uint8_t)x)");
  }
}
