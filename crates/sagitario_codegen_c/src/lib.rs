//! C11 code generation from SIR (docs/architecture.md#c-code-generation). The output is strict,
//! portable C11 that includes `sagitario_runtime.h`. Integer arithmetic, negation, indexing and
//! float-to-integer casts go through runtime helpers so the generated C has no undefined
//! behavior; the helpers receive `__FILE__`/`__LINE__`, which `#line` maps back to the source.
//!
//! Structs become C structs `sag_sN` (fields `fN`). Enums become `sag_eN` and each array,
//! `Option` and `Result` type a `sag_tN`: arrays wrap a C array, enum-like types hold a `tag`
//! (the variant's index) and a union `u` with one struct `vN` per variant that has fields. All
//! are copied by assignment and passed by value. Managed aggregates (containing `String`s) get
//! `sag_retain_*`/`sag_release_*` functions.
//!
//! A class is a heap object `sag_cN` whose first member is its parent's struct (`base`) or, for
//! a class without parent, the runtime's `sag_object` header (reference counts, drop function,
//! vtable). Values of every class are `sag_object *`, so an instance passes for any of its
//! ancestors; a field is read by converting the pointer to the struct of the class that declares
//! it, which C allows because each struct starts with its parent's. `sag_new_cN` allocates a
//! zeroed instance, `sag_drop_cN` releases the class's fields and then its parent's, and
//! `sag_vtable_cN` lists the methods called through the vtable.

use sagitario_ast::{BinaryOp, UnaryOp};
use sagitario_resolve::{Builtin, ClassId, EnumId, FnId, StructId};
use sagitario_sir::{
  Callee, Const, ExternDecl, Function, Layouts, Local, Operand, PanicMessage, Place, Program, Projection, Rvalue, Stmt, TemplatePiece,
};
use sagitario_types::{ClassRef, EnumRef, FloatTy, IntTy, StructRef, Type};

pub const RUNTIME_HEADER: &str = "sagitario_runtime.h";

/// The C translation units of a program.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedC {
  /// The program, which includes the runtime header.
  pub program: String,
  /// The calls into C and the exported functions, compiled apart without system headers so the
  /// program's own declarations of C functions cannot clash with them; `None` without FFI.
  pub ffi: Option<String>,
}

pub fn generate(program: &Program) -> GeneratedC {
  let mut generator = Generator {
    layouts: &program.layouts,
    instances: Vec::new(),
    out: String::new(),
    indent: 0,
    paths: program.source_paths.iter().map(|path| c_string_literal(path.as_bytes())).collect(),
    locals: &[],
    self_by_ref: false,
    source_line: None,
    pointees: Vec::new(),
    classes: Vec::new(),
    functions: &program.functions,
  };
  let order = generator.aggregate_order(program);

  generator.out.push_str("/* Generated by sag. Do not edit. */\n");
  generator.out.push_str(&format!("#include \"{RUNTIME_HEADER}\"\n\n"));
  generator.type_definitions(&order);

  for (index, decl) in program.externs.iter().enumerate() {
    let prototype = generator.extern_prototype(index, decl);

    generator.out.push_str(&format!("{prototype};\n"));
  }

  for (index, function) in program.functions.iter().enumerate() {
    let signature = generator.signature(FnId(index as u32), function);

    generator.out.push_str(&format!("{}{signature};\n", linkage(function)));
  }

  generator.out.push('\n');
  generator.class_support(&order);

  for (index, function) in program.functions.iter().enumerate() {
    generator.function(FnId(index as u32), function);
  }

  generator.entry_point(program);

  let ffi = generator.ffi_unit(program);

  GeneratedC { program: generator.out, ffi }
}

/// Exported functions are called from the FFI translation unit; the others stay private.
fn linkage(function: &Function) -> &'static str {
  if function.export.is_some() { "" } else { "static " }
}

/// A C struct to define: a struct, an enum, a class's objects, or an array, `Option` or
/// `Result` type (index in `Generator::instances`).
#[derive(Clone, Copy)]
enum Aggregate {
  Struct(usize),
  Enum(usize),
  Class(usize),
  Instance(usize),
}

struct Generator<'a> {
  layouts: &'a Layouts,
  /// Every array, `Option` and `Result` type used by the program; `sag_tN` is the one at index
  /// `N`.
  instances: Vec<Type>,
  out: String,
  indent: usize,
  /// The source paths as C string literals, by file index, for `#line`.
  paths: Vec<String>,
  /// Locals of the function being generated.
  locals: &'a [Type],
  /// Whether local 0 of the function being generated is a pointer (`var self`).
  self_by_ref: bool,
  /// The source file and line of the statement being generated.
  source_line: Option<(u32, u32)>,
  /// Types behind pointers, given a C type after the aggregate being visited.
  pointees: Vec<Type>,
  /// Classes whose objects are referenced, defined after the aggregate being visited.
  classes: Vec<usize>,
  /// The program's functions, for the signatures of calls through vtables.
  functions: &'a [Function],
}

impl<'a> Generator<'a> {
  /// Every aggregate type, each after the ones it contains, as C requires.
  fn aggregate_order(&mut self, program: &Program) -> Vec<Aggregate> {
    let mut order = Vec::new();
    let mut done = vec![false; self.layouts.structs.len() + self.layouts.enums.len() + self.layouts.classes.len()];

    for index in 0..self.layouts.structs.len() {
      self.visit_type(&struct_type(index), &mut done, &mut order);
    }

    for index in 0..self.layouts.enums.len() {
      self.visit_type(&enum_type(index), &mut done, &mut order);
    }

    for index in 0..self.layouts.classes.len() {
      self.classes.push(index);
    }

    for function in &program.functions {
      for ty in function.locals.iter().chain([&function.ret]) {
        self.visit_type(ty, &mut done, &mut order);
      }
    }

    for decl in &program.externs {
      for ty in decl.params.iter().chain([&decl.ret]) {
        self.visit_type(ty, &mut done, &mut order);
      }
    }

    // A pointer only needs its pointee declared, so pointees and classes may come in any order
    // (and a struct or class may point to itself).
    loop {
      if let Some(pointee) = self.pointees.pop() {
        self.visit_type(&pointee, &mut done, &mut order);
      } else if let Some(class) = self.classes.pop() {
        self.visit_class(class, &mut done, &mut order);
      } else {
        break;
      }
    }

    order
  }

  /// Defines a class's objects after the types of its fields.
  fn visit_class(&mut self, index: usize, done: &mut [bool], order: &mut Vec<Aggregate>) {
    let flag = self.layouts.structs.len() + self.layouts.enums.len() + index;

    if done.get(flag).copied().unwrap_or(true) {
      return;
    }

    if let Some(slot) = done.get_mut(flag) {
      *slot = true;
    }

    // An object contains its parent's part by value.
    if let Some(parent) = self.layouts.class(ClassId(index as u32)).and_then(|layout| layout.parent) {
      self.visit_class(parent.0 as usize, done, order);
    }

    for field in self.layouts.class_fields(ClassId(index as u32)) {
      self.visit_type(&field, done, order);
    }

    order.push(Aggregate::Class(index));
  }

  /// `done` flags structs first, then enums, then classes.
  fn visit_type(&mut self, ty: &Type, done: &mut [bool], order: &mut Vec<Aggregate>) {
    let (flag, aggregate) = match ty {
      Type::Struct(inner) => (inner.id.0 as usize, Aggregate::Struct(inner.id.0 as usize)),
      Type::Enum(inner) => (self.layouts.structs.len() + inner.id.0 as usize, Aggregate::Enum(inner.id.0 as usize)),
      Type::Class(inner) => {
        self.classes.push(inner.id.0 as usize);

        return;
      }
      Type::Array(..) | Type::Option(_) | Type::Result(..) => {
        if self.instances.contains(ty) {
          return;
        }

        for part in self.parts(ty).iter().flatten() {
          self.visit_type(part, done, order);
        }

        self.instances.push(ty.clone());
        order.push(Aggregate::Instance(self.instances.len() - 1));

        return;
      }
      Type::Ptr { pointee, .. } => {
        self.pointees.push(pointee.as_ref().clone());

        return;
      }
      _ => return,
    };

    if done.get(flag).copied().unwrap_or(true) {
      return;
    }

    if let Some(slot) = done.get_mut(flag) {
      *slot = true;
    }

    for part in self.parts(ty).iter().flatten() {
      self.visit_type(part, done, order);
    }

    order.push(aggregate);
  }

  /// The types a value of `ty` contains: per variant for enum-like types, else one group.
  fn parts(&self, ty: &Type) -> Vec<Vec<Type>> {
    match ty {
      Type::Struct(inner) => vec![self.layouts.struct_fields(inner.id)],
      Type::Class(inner) => vec![self.layouts.class_fields(inner.id)],
      Type::Array(elem, _) => vec![vec![elem.as_ref().clone()]],
      _ => self.layouts.variants(ty).unwrap_or_default(),
    }
  }

  fn aggregate_type(&self, aggregate: Aggregate) -> Type {
    match aggregate {
      Aggregate::Struct(index) => struct_type(index),
      Aggregate::Enum(index) => enum_type(index),
      Aggregate::Class(index) => class_type(index),
      Aggregate::Instance(index) => self.instances.get(index).cloned().unwrap_or(Type::Error),
    }
  }

  /// The C struct of an aggregate: for a class, the struct of its objects.
  fn struct_name(&self, ty: &Type) -> String {
    match ty {
      Type::Class(inner) => format!("sag_c{}", inner.id.0),
      _ => self.c_type(ty),
    }
  }

  fn type_definitions(&mut self, order: &[Aggregate]) {
    // Declared first, so pointers can refer to any of them.
    for aggregate in order {
      let name = self.struct_name(&self.aggregate_type(*aggregate));

      self.out.push_str(&format!("typedef struct {name} {name};\n"));
    }

    for aggregate in order {
      let ty = self.aggregate_type(*aggregate);
      let definition = self.definition(&ty);

      self.out.push_str(&definition);
    }

    for aggregate in order {
      self.arc_functions(*aggregate);
    }

    self.out.push('\n');
  }

  /// The vtables, then the functions that create and destroy instances, after the prototypes
  /// of the methods the vtables list.
  fn class_support(&mut self, order: &[Aggregate]) {
    for aggregate in order {
      if let Aggregate::Class(index) = aggregate {
        let methods: Vec<String> = self
          .layouts
          .class(ClassId(*index as u32))
          .map(|layout| layout.vtable.iter().map(|function| format!("(sag_method){}", fn_name(*function))).collect())
          .unwrap_or_default();

        if !methods.is_empty() {
          self.out.push_str(&format!("static const sag_method sag_vtable_c{index}[] = {{ {} }};\n", methods.join(", ")));
        }
      }
    }

    for aggregate in order {
      if let Aggregate::Class(index) = aggregate {
        self.class_functions(*index);
      }
    }

    self.out.push('\n');
  }

  /// The vtable of a class as a C expression: `sag_vtable_cN`, or `NULL` when it is empty.
  fn vtable(&self, class: ClassId) -> String {
    match self.layouts.class(class) {
      Some(layout) if !layout.vtable.is_empty() => format!("sag_vtable_c{}", class.0),
      _ => "NULL".to_string(),
    }
  }

  /// `sag_drop_cN`, which releases the fields of an object (its own, then its parent's), and
  /// `sag_new_cN`.
  fn class_functions(&mut self, index: usize) {
    let name = format!("sag_c{index}");
    let parent = self.layouts.class(ClassId(index as u32)).and_then(|layout| layout.parent);
    let releases: Vec<String> = self
      .layouts
      .class_fields(ClassId(index as u32))
      .iter()
      .enumerate()
      .filter(|(_, field)| self.layouts.is_managed(field))
      .map(|(field, ty)| format!("  {};\n", self.arc_call("release", ty, &format!("value->f{field}"))))
      .collect();

    self.out.push_str(&format!("static void sag_drop_c{index}(sag_object *object) {{\n"));

    if releases.is_empty() {
      self.out.push_str("  (void)object;\n");
    } else {
      self.out.push_str(&format!("  {name} *value = ({name} *)object;\n{}", releases.concat()));
    }

    if let Some(parent) = parent {
      self.out.push_str(&format!("  sag_drop_c{}(object);\n", parent.0));
    }

    let vtable = self.vtable(ClassId(index as u32));

    self.out.push_str("}\n");
    self.out.push_str(&format!("static sag_object *sag_new_c{index}(void) {{\n"));
    self.out.push_str(&format!("  {name} *value = sag_object_alloc(sizeof({name}));\n"));
    self.out.push_str(&format!("  *value = ({name}){{0}};\n"));
    self.out.push_str(&format!("  sag_object_init((sag_object *)value, sag_drop_c{index}, {vtable});\n"));
    self.out.push_str("  return (sag_object *)value;\n}\n");
  }

  /// `struct sag_xN { ... };` for an aggregate type.
  fn definition(&self, ty: &Type) -> String {
    let name = self.struct_name(ty);
    let members = match ty {
      Type::Class(inner) => {
        let fields = self.parts(ty).concat();
        let members: Vec<String> = fields.iter().enumerate().map(|(index, field)| format!(" {} f{index};", self.c_type(field))).collect();
        let base = match self.layouts.class(inner.id).and_then(|layout| layout.parent) {
          Some(parent) => format!("sag_c{} base;", parent.0),
          None => "sag_object header;".to_string(),
        };

        format!("{base}{}", members.concat())
      }
      Type::Struct(_) => {
        let fields = self.parts(ty).concat();
        let mut members: Vec<String> = fields.iter().enumerate().map(|(index, field)| format!("{} f{index};", self.c_type(field))).collect();

        if members.is_empty() {
          // C has no empty structs.
          members.push("uint8_t sag_unused;".to_string());
        }

        members.join(" ")
      }
      Type::Array(elem, len) => {
        // C has no zero-length arrays; the extra element is never accessed.
        format!("{} data[{}];", self.c_type(elem), len.max(&1))
      }
      _ => {
        let variants: Vec<String> = self
          .parts(ty)
          .iter()
          .enumerate()
          .filter(|(_, fields)| !fields.is_empty())
          .map(|(index, fields)| {
            let fields: Vec<String> = fields.iter().enumerate().map(|(field, field_ty)| format!("{} f{field};", self.c_type(field_ty))).collect();

            format!("struct {{ {} }} v{index};", fields.join(" "))
          })
          .collect();

        if variants.is_empty() { "uint32_t tag;".to_string() } else { format!("uint32_t tag; union {{ {} }} u;", variants.join(" ")) }
      }
    };

    format!("struct {name} {{ {members} }};\n")
  }

  /// `sag_retain_*` and `sag_release_*` for a managed aggregate.
  fn arc_functions(&mut self, aggregate: Aggregate) {
    let ty = self.aggregate_type(aggregate);

    // Class references use the runtime's `sag_object_retain`/`sag_object_release`.
    if !self.layouts.is_managed(&ty) || matches!(aggregate, Aggregate::Class(_)) {
      return;
    }

    let name = self.c_type(&ty);
    let suffix = name.trim_start_matches("sag_").to_string();

    for action in ["retain", "release"] {
      let mut body = Vec::new();

      match &ty {
        Type::Struct(_) => {
          for (index, field) in self.parts(&ty).concat().iter().enumerate() {
            if self.layouts.is_managed(field) {
              body.push(format!("  {};", self.arc_call(action, field, &format!("value->f{index}"))));
            }
          }
        }
        Type::Array(elem, len) => {
          let call = self.arc_call(action, elem, "value->data[sag_k]");

          body.push(format!("  for (size_t sag_k = 0; sag_k < {len}; sag_k++) {{ {call}; }}"));
        }
        _ => {
          body.push("  switch (value->tag) {".to_string());

          for (variant, fields) in self.parts(&ty).iter().enumerate() {
            let calls: Vec<String> = fields
              .iter()
              .enumerate()
              .filter(|(_, field)| self.layouts.is_managed(field))
              .map(|(index, field)| format!("{}; ", self.arc_call(action, field, &format!("value->u.v{variant}.f{index}"))))
              .collect();

            if !calls.is_empty() {
              body.push(format!("  case {variant}: {}break;", calls.concat()));
            }
          }

          body.push("  default: break;".to_string());
          body.push("  }".to_string());
        }
      }

      self.out.push_str(&format!("static void sag_{action}_{suffix}(const {name} *value) {{\n{}\n}}\n", body.join("\n")));
    }
  }

  /// A call that retains or releases the managed value `value` (an lvalue unless a `String`).
  fn arc_call(&self, action: &str, ty: &Type, value: &str) -> String {
    match ty {
      Type::String => format!("sag_string_{action}({value})"),
      Type::StringBuilder => format!("sag_builder_{action}({value})"),
      Type::CString => format!("sag_cstring_{action}({value})"),
      Type::Class(_) => format!("sag_object_{action}({value})"),
      _ => format!("sag_{action}_{}(&{value})", self.c_type(ty).trim_start_matches("sag_")),
    }
  }

  fn instance_index(&self, ty: &Type) -> usize {
    self.instances.iter().position(|instance| instance == ty).unwrap_or(0)
  }

  /// The C type of a stored value. `()` has no data but is stored as a byte so it can be a
  /// parameter or local.
  fn c_type(&self, ty: &Type) -> String {
    match ty {
      Type::Unit | Type::Never | Type::Error => "uint8_t".to_string(),
      Type::Bool => "bool".to_string(),
      Type::Char => "uint32_t".to_string(),
      Type::Int(int) => int_c_type(*int).to_string(),
      Type::Float(FloatTy::F32) => "float".to_string(),
      Type::Float(FloatTy::F64) => "double".to_string(),
      Type::String => "sag_string".to_string(),
      Type::StringBuilder => "sag_builder".to_string(),
      Type::Struct(inner) => format!("sag_s{}", inner.id.0),
      Type::Enum(inner) => format!("sag_e{}", inner.id.0),
      Type::Class(_) => "sag_object *".to_string(),
      Type::Array(..) | Type::Option(_) | Type::Result(..) => format!("sag_t{}", self.instance_index(ty)),
      Type::CString => "sag_cstring".to_string(),
      Type::CVoid => "void".to_string(),
      Type::Ptr { mutable, pointee } => format!("{}{}*", self.c_type(pointee), if *mutable { "" } else { " const" }),
    }
  }

  /// The C `main`: runs the entry function and turns an `Err` from `main` into exit code 1.
  fn entry_point(&mut self, program: &Program) {
    let entry = fn_name(program.entry);
    let returns_result = program.functions.get(program.entry.0 as usize).is_some_and(|function| matches!(function.ret, Type::Result(..)));

    self.out.push_str("int main(int argc, char **argv) {\n");
    self.out.push_str("  sag_rt_init(argc, argv);\n");

    if let Some(function) = program.functions.get(program.entry.0 as usize).filter(|_| returns_result) {
      let ty = self.c_type(&function.ret);

      self.out.push_str(&format!("  {ty} result = {entry}();\n"));
      self.out.push_str("  if (result.tag == 1) {\n");
      self.out.push_str("    sag_report_main_error(result.u.v1.f0);\n");
      self.out.push_str("    sag_string_release(result.u.v1.f0);\n");
      self.out.push_str("    int code = sag_rt_finish();\n");
      self.out.push_str("    return code != 0 ? code : 1;\n");
      self.out.push_str("  }\n");
    } else {
      self.out.push_str(&format!("  {entry}();\n"));
    }

    self.out.push_str("  return sag_rt_finish();\n");
    self.out.push_str("}\n");
  }

  /// `ret sag_ffi_N(params)`, the wrapper calling a C function.
  fn extern_prototype(&self, index: usize, decl: &ExternDecl) -> String {
    format!("{} {}({})", self.return_type(&decl.ret), ffi_name(index), self.c_params(&decl.params))
  }

  fn return_type(&self, ty: &Type) -> String {
    if matches!(ty, Type::Unit | Type::Never) { "void".to_string() } else { self.c_type(ty) }
  }

  /// `T a0, U a1`, or `void`.
  fn c_params(&self, params: &[Type]) -> String {
    let params: Vec<String> = params.iter().enumerate().map(|(index, ty)| format!("{} a{index}", self.c_type(ty))).collect();

    if params.is_empty() { "void".to_string() } else { params.join(", ") }
  }

  /// The FFI translation unit: a wrapper per C function the program calls, and a function with
  /// the exported symbol per `extern "C" fn`. It includes no system header, so the program's
  /// declarations of C functions are the only ones it sees.
  fn ffi_unit(&self, program: &Program) -> Option<String> {
    let exports: Vec<(usize, &Function, &String)> =
      program.functions.iter().enumerate().filter_map(|(index, function)| function.export.as_ref().map(|symbol| (index, function, symbol))).collect();

    if program.externs.is_empty() && exports.is_empty() {
      return None;
    }

    let mut declared = Vec::new();
    let mut defined = Vec::new();
    let signature_types = program.externs.iter().flat_map(|decl| decl.params.iter().chain([&decl.ret]));
    let export_types = exports.iter().flat_map(|(_, function, _)| function.locals.iter().take(function.param_count).chain([&function.ret]));

    for ty in signature_types.chain(export_types) {
      self.ffi_types(ty, true, &mut declared, &mut defined);
    }

    let mut out = String::from("/* Generated by sag: calls between the program and C. Do not edit. */\n");

    out.push_str("#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n");

    for name in &declared {
      out.push_str(&format!("typedef struct {name} {name};\n"));
    }

    for ty in &defined {
      out.push_str(&self.definition(ty));
    }

    for (index, decl) in program.externs.iter().enumerate() {
      let args: Vec<String> = (0..decl.params.len()).map(|arg| format!("a{arg}")).collect();
      let call = format!("{}({})", decl.symbol, args.join(", "));
      let body = if matches!(decl.ret, Type::Unit | Type::Never) { format!("{call};") } else { format!("return {call};") };
      let ret = self.return_type(&decl.ret);
      let params = self.c_params(&decl.params);

      out.push_str(&format!("\nextern {ret} {}({params});\n", decl.symbol));
      out.push_str(&format!("{} {{ {body} }}\n", self.extern_prototype(index, decl)));
    }

    for (index, function, symbol) in exports {
      let id = FnId(index as u32);
      let params: Vec<Type> = function.locals.iter().take(function.param_count).cloned().collect();
      let args: Vec<String> = (0..params.len()).map(|arg| format!("a{arg}")).collect();
      let call = format!("{}({})", fn_name(id), args.join(", "));
      let body = if matches!(function.ret, Type::Unit | Type::Never) { format!("{call};") } else { format!("return {call};") };

      out.push_str(&format!("\n{};\n", self.signature(id, function)));
      out.push_str(&format!("{} {symbol}({}) {{ {body} }}\n", self.return_type(&function.ret), self.c_params(&params)));
    }

    Some(out)
  }

  /// Collects the aggregate types the FFI unit needs: declared when behind a pointer, also
  /// defined when passed by value (`@repr(C)` structs and their fields).
  fn ffi_types(&self, ty: &Type, by_value: bool, declared: &mut Vec<String>, defined: &mut Vec<Type>) {
    match ty {
      Type::Ptr { pointee, .. } => self.ffi_types(pointee, false, declared, defined),
      Type::Struct(_) | Type::Enum(_) | Type::Array(..) | Type::Option(_) | Type::Result(..) => {
        let name = self.c_type(ty);

        if !declared.contains(&name) {
          declared.push(name);
        }

        if by_value && !defined.contains(ty) {
          for part in self.parts(ty).concat() {
            self.ffi_types(&part, true, declared, defined);
          }

          defined.push(ty.clone());
        }
      }
      _ => {}
    }
  }

  fn line_directive(&mut self, file: u32, line: u32) {
    let path = self.paths.get(file as usize).map_or("\"?\"", String::as_str);

    self.out.push_str(&format!("#line {line} {path}\n"));
  }

  fn line(&mut self, text: &str) {
    // One statement may become several C lines; a runtime check reports `__LINE__`, so the
    // source line is restated right before it.
    if text.contains("__LINE__")
      && let Some((file, line)) = self.source_line
    {
      self.line_directive(file, line);
    }

    for _ in 0..self.indent {
      self.out.push_str("  ");
    }

    self.out.push_str(text);
    self.out.push('\n');
  }

  /// The C type of a pointer to a method, to call one taken from a vtable.
  fn method_pointer(&self, id: FnId) -> String {
    let Some(function) = self.functions.get(id.0 as usize) else { return "void (*)(void)".to_string() };
    let params: Vec<String> = function.locals.iter().take(function.param_count).map(|ty| self.c_type(ty)).collect();

    format!("{} (*)({})", self.return_type(&function.ret), params.join(", "))
  }

  fn signature(&self, id: FnId, function: &Function) -> String {
    let params: Vec<String> = function
      .locals
      .iter()
      .take(function.param_count)
      .enumerate()
      .map(|(index, ty)| {
        let pointer = if index == 0 && function.self_by_ref { " *" } else { " " };

        format!("{}{pointer}{}", self.c_type(ty), local_name(Local(index as u32)))
      })
      .collect();
    let params = if params.is_empty() { "void".to_string() } else { params.join(", ") };
    let ret = if matches!(function.ret, Type::Unit | Type::Never) { "void".to_string() } else { self.c_type(&function.ret) };

    format!("{ret} {}({params})", fn_name(id))
  }

  fn function(&mut self, id: FnId, function: &'a Function) {
    let signature = self.signature(id, function);

    self.locals = &function.locals;
    self.self_by_ref = function.self_by_ref;
    self.out.push_str(&format!("{}{signature} {{\n", linkage(function)));
    self.indent = 1;

    for (index, ty) in function.locals.iter().enumerate().skip(function.param_count) {
      let init =
        if matches!(ty, Type::String | Type::Struct(_) | Type::Enum(_) | Type::Array(..) | Type::Option(_) | Type::Result(..)) { "{0}" } else { "0" };

      self.line(&format!("{} {} = {init};", self.c_type(ty), local_name(Local(index as u32))));
    }

    self.stmts(&function.body);
    self.indent = 0;
    self.out.push_str("}\n\n");
  }

  fn local_type(&self, local: Local) -> Type {
    self.locals.get(local.0 as usize).cloned().unwrap_or(Type::Error)
  }

  /// A local as an lvalue; the `var self` parameter is a pointer.
  fn local(&self, local: Local) -> String {
    if self.self_by_ref && local.0 == 0 { "(*l0)".to_string() } else { local_name(local) }
  }

  fn place(&self, place: &Place) -> String {
    let mut out = self.local(place.local);

    for projection in &place.projections {
      match projection {
        Projection::Field(index) => out.push_str(&format!(".f{index}")),
        Projection::ClassField { class, index } => out = format!("((sag_c{} *){out})->f{index}", class.0),
        Projection::Index { index, len } => {
          out.push_str(&format!(".data[sag_index_at({}, {len}, __FILE__, __LINE__)]", self.operand(index)));
        }
        Projection::Tag => out.push_str(".tag"),
        Projection::VariantField { variant, field } => out.push_str(&format!(".u.v{variant}.f{field}")),
        Projection::Deref => out = format!("(*SAG_CHECK_PTR({out}, __FILE__, __LINE__))"),
      }
    }

    out
  }

  fn operand(&self, operand: &Operand) -> String {
    match operand {
      Operand::Local(target) => self.local(*target),
      Operand::Place(place) => self.place(place),
      Operand::Ref(place) => format!("(&{})", self.place(place)),
      Operand::Const(value) => constant(value),
    }
  }

  fn operand_type(&self, operand: &Operand) -> Type {
    match operand {
      Operand::Local(local) => self.local_type(*local),
      Operand::Place(place) | Operand::Ref(place) => place.ty.clone(),
      Operand::Const(Const::Str(_)) => Type::String,
      Operand::Const(_) => Type::Unit,
    }
  }

  fn stmts(&mut self, stmts: &[Stmt]) {
    for stmt in stmts {
      self.stmt(stmt);
    }
  }

  fn block(&mut self, header: &str, body: &[Stmt]) {
    self.line(&format!("{header} {{"));
    self.indent += 1;
    self.stmts(body);
    self.indent -= 1;
    self.line("}");
  }

  fn stmt(&mut self, stmt: &Stmt) {
    match stmt {
      // `#line` must start at column 0 to stay readable; C ignores the indentation anyway.
      Stmt::Line { file, line } => {
        self.source_line = Some((*file, *line));
        self.line_directive(*file, *line);
      }
      Stmt::Assign { dest, value } => {
        let ty = self.local_type(*dest);
        let dest = self.local(*dest);

        self.assign(&dest, &ty, value);
      }
      Stmt::AssignPlace { dest, value } => {
        let target = self.place(dest);

        self.assign(&target, &dest.ty, value);
      }
      Stmt::Eval(value) => {
        let value = self.rvalue(value, &Type::Unit);

        self.line(&format!("{value};"));
      }
      Stmt::Retain(value) => {
        let ty = self.operand_type(value);
        let call = self.arc_call("retain", &ty, &self.operand(value));

        self.line(&format!("{call};"));
      }
      Stmt::Release(target) => {
        let call = self.arc_call("release", &self.local_type(*target), &self.local(*target));

        self.line(&format!("{call};"));
      }
      Stmt::ReleasePlace(target) => {
        let call = self.arc_call("release", &target.ty, &self.place(target));

        self.line(&format!("{call};"));
      }
      Stmt::Reset(target) => {
        let ty = self.local_type(*target);
        let value = if ty == Type::String { "sag_string_empty()".to_string() } else { format!("({}){{0}}", self.c_type(&ty)) };

        self.line(&format!("{} = {value};", self.local(*target)));
      }
      Stmt::If { cond, then_body, else_body } => {
        self.block(&format!("if ({})", self.operand(cond)), then_body);

        if !else_body.is_empty() {
          self.block("else", else_body);
        }
      }
      Stmt::Loop { body } => self.block("for (;;)", body),
      Stmt::ForRange { var, ty, start, end, inclusive, body } => {
        let c_ty = int_c_type(*ty);
        let counter = format!("sag_i{}", var.0);
        let (start, end) = (self.operand(start), self.operand(end));
        // A `continue` jumps to the increment, which must never step past `end` (it may be the
        // type's maximum), so the closed form tracks completion in a separate flag.
        let header = if *inclusive {
          let done = format!("sag_done{}", var.0);

          format!(
            "for ({c_ty} {counter} = {start}, {done} = ({c_ty})({start} > {end}); {done} == 0; \
             {done} = ({c_ty})({counter} == {end}), {counter} = {done} ? {counter} : ({c_ty})({counter} + 1))"
          )
        } else {
          format!("for ({c_ty} {counter} = {start}; {counter} < {end}; {counter} = ({c_ty})({counter} + 1))")
        };

        self.line(&format!("{header} {{"));
        self.indent += 1;
        self.line(&format!("{} = {counter};", self.local(*var)));
        self.stmts(body);
        self.indent -= 1;
        self.line("}");
      }
      Stmt::ForArray { var, array, len, body } => {
        let counter = format!("sag_i{}", var.0);

        self.line(&format!("for (size_t {counter} = 0; {counter} < {len}; {counter}++) {{"));
        self.indent += 1;
        self.line(&format!("{} = {}.data[{counter}];", self.local(*var), self.local(*array)));
        self.stmts(body);
        self.indent -= 1;
        self.line("}");
      }
      Stmt::ForText { var, text, bytes, body } => {
        let counter = format!("sag_i{}", var.0);
        let (text, var) = (self.local(*text), self.local(*var));

        // `sag_utf8_next` advances the index, so `continue` needs no increment step.
        if *bytes {
          self.line(&format!("for (size_t {counter} = 0; {counter} < {text}.len; {counter}++) {{"));
          self.indent += 1;
          self.line(&format!("{var} = {text}.ptr[{counter}];"));
        } else {
          self.line(&format!("for (size_t {counter} = 0; {counter} < {text}.len;) {{"));
          self.indent += 1;
          self.line(&format!("{var} = sag_utf8_next({text}, &{counter});"));
        }

        self.stmts(body);
        self.indent -= 1;
        self.line("}");
      }
      Stmt::SetVtable { object, class } => {
        let vtable = self.vtable(*class);

        self.line(&format!("{}->vtable = {vtable};", self.local(*object)));
      }
      Stmt::Break => self.line("break;"),
      Stmt::Continue => self.line("continue;"),
      Stmt::Return(None) => self.line("return;"),
      Stmt::Return(Some(value)) => {
        let value = self.operand(value);

        self.line(&format!("return {value};"));
      }
      Stmt::Panic(PanicMessage::Static(message)) => {
        let message = c_string_literal(message.as_bytes());

        self.line(&format!("sag_panic_at({message}, __FILE__, __LINE__);"));
      }
      Stmt::Panic(PanicMessage::Value(message)) => {
        let message = self.operand(message);

        self.line(&format!("sag_panic_str_at({message}, __FILE__, __LINE__);"));
      }
    }
  }

  /// `dest = value;` where `dest` is an lvalue of type `ty`.
  fn assign(&mut self, dest: &str, ty: &Type, value: &Rvalue) {
    match value {
      Rvalue::Template(pieces) => self.template(dest, pieces),
      Rvalue::Repeat(element) => {
        let Type::Array(elem_ty, len) = ty else { return };
        let element = self.operand(element);
        let retain = self.layouts.is_managed(elem_ty).then(|| self.arc_call("retain", elem_ty, &format!("{dest}.data[sag_k]")));

        self.line(&format!("for (size_t sag_k = 0; sag_k < {len}; sag_k++) {{"));
        self.indent += 1;
        self.line(&format!("{dest}.data[sag_k] = {element};"));

        if let Some(retain) = retain {
          self.line(&format!("{retain};"));
        }

        self.indent -= 1;
        self.line("}");
      }
      _ => {
        let value = self.rvalue(value, ty);

        self.line(&format!("{dest} = {value};"));
      }
    }
  }

  /// An rvalue stored into a destination of type `ty`.
  fn rvalue(&self, value: &Rvalue, ty: &Type) -> String {
    match value {
      Rvalue::Use(value) => self.operand(value),
      Rvalue::Unary { op: UnaryOp::Not, operand: value, .. } => format!("(!{})", self.operand(value)),
      Rvalue::Unary { op: UnaryOp::Neg, ty: Type::Int(int), operand: value } => {
        format!("sag_neg_{}_at({}, __FILE__, __LINE__)", int.name(), self.operand(value))
      }
      Rvalue::Unary { op: UnaryOp::Neg, operand: value, .. } => format!("(-{})", self.operand(value)),
      // Dereferences are places (`Projection::Deref`); this form is not produced.
      Rvalue::Unary { op: UnaryOp::Deref, operand: value, .. } => format!("(*{})", self.operand(value)),
      Rvalue::Binary { op, ty, lhs, rhs } => binary(*op, ty, &self.operand(lhs), &self.operand(rhs)),
      Rvalue::Cast { from, to, operand: value } => match (from, to) {
        (Type::Ptr { .. }, Type::Ptr { .. }) => format!("(({}){})", self.c_type(to), self.operand(value)),
        (Type::Int(_), Type::Ptr { .. }) => format!("(({})(uintptr_t){})", self.c_type(to), self.operand(value)),
        (Type::Ptr { .. }, Type::Int(int)) => format!("(({})(uintptr_t){})", int_c_type(*int), self.operand(value)),
        _ => cast(from, to, &self.operand(value)),
      },
      Rvalue::Call { callee: Callee::Virtual { slot, function }, args } => {
        let args: Vec<String> = args.iter().map(|arg| self.operand(arg)).collect();
        let receiver = args.first().cloned().unwrap_or_default();

        format!("(({})({receiver}->vtable[{slot}]))({})", self.method_pointer(*function), args.join(", "))
      }
      Rvalue::Call { callee, args } => {
        let mut args: Vec<String> = args.iter().map(|arg| self.operand(arg)).collect();

        // Runtime functions that can panic report the source location.
        if matches!(callee, Callee::Runtime { located: true, .. } | Callee::Builtin(Builtin::Panic | Builtin::StringFromC)) {
          args.push("__FILE__".to_string());
          args.push("__LINE__".to_string());
        }

        format!("{}({})", callee_name(*callee), args.join(", "))
      }
      Rvalue::Aggregate(parts) => {
        let parts: Vec<String> = parts.iter().map(|part| self.operand(part)).collect();
        let parts = if parts.is_empty() { "0".to_string() } else { parts.join(", ") };

        match ty {
          Type::Array(..) => format!("({}){{{{{parts}}}}}", self.c_type(ty)),
          _ => format!("({}){{{parts}}}", self.c_type(ty)),
        }
      }
      Rvalue::Variant { index, fields } => {
        let fields: Vec<String> = fields.iter().map(|field| self.operand(field)).collect();

        if fields.is_empty() {
          format!("({}){{.tag = {index}u}}", self.c_type(ty))
        } else {
          format!("({}){{.tag = {index}u, .u.v{index} = {{{}}}}}", self.c_type(ty), fields.join(", "))
        }
      }
      Rvalue::Alloc(class) => format!("sag_new_c{}()", class.0),
      // Templates and repeats are emitted as statements by `Generator::assign`.
      Rvalue::Template(_) | Rvalue::Repeat(_) => "0".to_string(),
    }
  }

  fn template(&mut self, dest: &str, pieces: &[TemplatePiece]) {
    self.line("{");
    self.indent += 1;
    self.line("sag_sb sag_template;");
    self.line("sag_sb_init(&sag_template);");

    for piece in pieces {
      let push = match piece {
        TemplatePiece::Text(text) => {
          format!("sag_sb_push_bytes(&sag_template, {}, {})", c_string_literal(text.as_bytes()), text.len())
        }
        TemplatePiece::Value(ty, value) => {
          let value = self.operand(value);

          match ty {
            Type::Int(int) if int.is_signed() => format!("sag_sb_push_i64(&sag_template, (int64_t)({value}))"),
            Type::Int(_) => format!("sag_sb_push_u64(&sag_template, (uint64_t)({value}))"),
            Type::Float(FloatTy::F32) => format!("sag_sb_push_f32(&sag_template, {value})"),
            Type::Float(FloatTy::F64) => format!("sag_sb_push_f64(&sag_template, {value})"),
            Type::Bool => format!("sag_sb_push_bool(&sag_template, {value})"),
            Type::Char => format!("sag_sb_push_char(&sag_template, {value})"),
            Type::String => format!("sag_sb_push_str(&sag_template, {value})"),
            // Diverging, erroneous or non-interpolable parts never reach code generation.
            Type::Unit
            | Type::StringBuilder
            | Type::Struct(_)
            | Type::Enum(_)
            | Type::Class(_)
            | Type::Array(..)
            | Type::Option(_)
            | Type::Result(..)
            | Type::Ptr { .. }
            | Type::CVoid
            | Type::CString
            | Type::Never
            | Type::Error => {
              continue;
            }
          }
        }
      };

      self.line(&format!("{push};"));
    }

    self.line(&format!("{dest} = sag_sb_finish(&sag_template);"));
    self.indent -= 1;
    self.line("}");
  }
}

fn struct_type(index: usize) -> Type {
  Type::Struct(StructRef { id: StructId(index as u32), name: String::new() })
}

fn enum_type(index: usize) -> Type {
  Type::Enum(EnumRef { id: EnumId(index as u32), name: String::new() })
}

fn class_type(index: usize) -> Type {
  Type::Class(ClassRef { id: ClassId(index as u32), name: String::new() })
}

/// Functions are named by id, so any Sagitario identifier (including Unicode) is safe in C.
fn fn_name(id: FnId) -> String {
  format!("sag_fn_{}", id.0)
}

/// The wrapper, in the FFI translation unit, that calls the C function of `extern` number `index`.
fn ffi_name(index: usize) -> String {
  format!("sag_ffi_{index}")
}

fn local_name(local: Local) -> String {
  format!("l{}", local.0)
}

fn int_c_type(int: IntTy) -> &'static str {
  match int {
    IntTy::I8 => "int8_t",
    IntTy::I16 => "int16_t",
    IntTy::I32 => "int32_t",
    IntTy::I64 => "int64_t",
    IntTy::Isize => "intptr_t",
    IntTy::U8 => "uint8_t",
    IntTy::U16 => "uint16_t",
    IntTy::U32 => "uint32_t",
    IntTy::U64 => "uint64_t",
    IntTy::Usize => "size_t",
  }
}

fn binary(op: BinaryOp, ty: &Type, lhs: &str, rhs: &str) -> String {
  let helper = match op {
    BinaryOp::Add => "add",
    BinaryOp::Sub => "sub",
    BinaryOp::Mul => "mul",
    BinaryOp::Div => "div",
    BinaryOp::Rem => "rem",
    // Comparisons are defined for every operand value; `&&`/`||` never reach here.
    _ => return format!("({lhs} {} {rhs})", op.symbol()),
  };

  match ty {
    Type::Int(int) => format!("sag_{helper}_{}_at({lhs}, {rhs}, __FILE__, __LINE__)", int.name()),
    Type::Float(FloatTy::F32) if op == BinaryOp::Rem => format!("fmodf({lhs}, {rhs})"),
    Type::Float(FloatTy::F64) if op == BinaryOp::Rem => format!("fmod({lhs}, {rhs})"),
    _ => format!("({lhs} {} {rhs})", op.symbol()),
  }
}

/// `as` conversions (docs/spec/02-types.md#conversions); only between primitive types.
fn cast(from: &Type, to: &Type, value: &str) -> String {
  match (from, to) {
    (from, to) if from == to => value.to_string(),
    (Type::Float(_), Type::Int(int)) => format!("sag_f2i_{}((double)({value}))", int.name()),
    (Type::Float(FloatTy::F64), Type::Float(FloatTy::F32)) => format!("sag_f64_to_f32({value})"),
    // Integer narrowing keeps the low bits (two's complement on every supported target);
    // widening, int-to-float rounding and bool/char conversions are exact C conversions.
    (_, Type::Int(int)) => format!("(({}){value})", int_c_type(*int)),
    (_, Type::Float(FloatTy::F32)) => format!("((float){value})"),
    (_, Type::Float(FloatTy::F64)) => format!("((double){value})"),
    (_, Type::Char) => format!("((uint32_t){value})"),
    _ => value.to_string(),
  }
}

fn callee_name(callee: Callee) -> String {
  match callee {
    Callee::Fn(id) | Callee::Virtual { function: id, .. } => fn_name(id),
    Callee::Extern(id) => ffi_name(id.0 as usize),
    Callee::Builtin(Builtin::Print) => "sag_print".to_string(),
    Callee::Builtin(Builtin::Println) => "sag_println".to_string(),
    Callee::Builtin(Builtin::Eprintln) => "sag_eprintln".to_string(),
    Callee::Builtin(Builtin::Panic) => "sag_panic_str_at".to_string(),
    Callee::Builtin(Builtin::StringFromC) => "sag_string_from_c_at".to_string(),
    // Lowered to a call of `sag_cstring_new` with its outputs.
    Callee::Builtin(Builtin::CStringNew) => "sag_cstring_new".to_string(),
    Callee::Runtime { function, .. } => function.to_string(),
  }
}

fn constant(value: &Const) -> String {
  match value {
    Const::Unit => "0".to_string(),
    Const::Bool(value) => value.to_string(),
    Const::Char(value) => format!("((uint32_t)0x{:X}u)", u32::from(*value)),
    Const::Int { value, negative: false, ty } => format!("(({}){value}ull)", int_c_type(*ty)),
    // `-(v - 1) - 1` avoids writing the positive magnitude of the minimum, which overflows.
    Const::Int { value, negative: true, ty } => match value.checked_sub(1) {
      Some(magnitude) => format!("(({})(-(int64_t){magnitude}ll - 1))", int_c_type(*ty)),
      None => format!("(({})0)", int_c_type(*ty)),
    },
    Const::Float(text, float) => {
      let text = if text.contains(['.', 'e']) { text.clone() } else { format!("{text}.0") };

      match float {
        FloatTy::F32 => format!("{text}f"),
        FloatTy::F64 => text,
      }
    }
    Const::Str(value) => {
      format!("sag_string_from_static({}, {})", c_string_literal(value.as_bytes()), value.len())
    }
  }
}

/// A C string literal holding exactly `bytes`. Anything outside printable ASCII becomes a
/// three-digit octal escape, which cannot merge with the following character. `?` is escaped to
/// avoid trigraphs.
fn c_string_literal(bytes: &[u8]) -> String {
  let mut out = String::from("\"");

  for &byte in bytes {
    match byte {
      b'"' => out.push_str("\\\""),
      b'\\' => out.push_str("\\\\"),
      b'?' => out.push_str("\\?"),
      b' '..=b'~' => out.push(char::from(byte)),
      _ => out.push_str(&format!("\\{byte:03o}")),
    }
  }

  out.push('"');
  out
}

