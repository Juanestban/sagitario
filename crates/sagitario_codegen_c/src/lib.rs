//! C11 code generation from SIR (docs/architecture.md#c-code-generation). The output is strict,
//! portable C11 that includes `sagitario_runtime.h`.

use sagitario_resolve::{Builtin, FnId};
use sagitario_sir::{Callee, Const, Function, Inst, Operand, Program};
use sagitario_types::{FloatTy, IntTy, Type};

pub const RUNTIME_HEADER: &str = "sagitario_runtime.h";

pub fn generate(program: &Program) -> String {
  let mut out = String::new();

  out.push_str("/* Generated by sag. Do not edit. */\n");
  out.push_str(&format!("#include \"{RUNTIME_HEADER}\"\n\n"));

  for (index, function) in program.functions.iter().enumerate() {
    out.push_str(&format!("static {};\n", signature(FnId(index as u32), function)));
  }

  out.push('\n');

  let path = c_string_literal(program.source_path.as_bytes());

  for (index, function) in program.functions.iter().enumerate() {
    out.push_str(&format!("static {} {{\n", signature(FnId(index as u32), function)));

    for inst in &function.body {
      match inst {
        Inst::Line(line) => out.push_str(&format!("#line {line} {path}\n")),
        Inst::Call { callee, args } => {
          let args: Vec<String> = args.iter().map(operand).collect();

          out.push_str(&format!("  {}({});\n", callee_name(*callee), args.join(", ")));
        }
        Inst::Eval(value) => out.push_str(&format!("  (void){};\n", operand(value))),
      }
    }

    out.push_str("}\n\n");
  }

  out.push_str("int main(int argc, char **argv) {\n");
  out.push_str("  sag_rt_init(argc, argv);\n");
  out.push_str(&format!("  {}();\n", fn_name(program.entry)));
  out.push_str("  return sag_rt_finish();\n");
  out.push_str("}\n");

  out
}

fn signature(id: FnId, function: &Function) -> String {
  let params: Vec<String> = function.params.iter().enumerate().map(|(index, ty)| format!("{} p{index}", c_type(ty))).collect();
  let params = if params.is_empty() { "void".to_string() } else { params.join(", ") };

  format!("{} {}({params})", c_type(&function.ret), fn_name(id))
}

/// Functions are named by id, so any Sagitario identifier (including Unicode) is safe in C.
fn fn_name(id: FnId) -> String {
  format!("sag_fn_{}", id.0)
}

fn callee_name(callee: Callee) -> String {
  match callee {
    Callee::Fn(id) => fn_name(id),
    Callee::Builtin(Builtin::Print) => "sag_print".to_string(),
    Callee::Builtin(Builtin::Println) => "sag_println".to_string(),
    Callee::Builtin(Builtin::Eprintln) => "sag_eprintln".to_string(),
  }
}

fn c_type(ty: &Type) -> &'static str {
  match ty {
    Type::Unit | Type::Error => "void",
    Type::Bool => "bool",
    Type::Char => "uint32_t",
    Type::Int(int) => int_c_type(*int),
    Type::Float(FloatTy::F32) => "float",
    Type::Float(FloatTy::F64) => "double",
    Type::String => "sag_string",
  }
}

fn int_c_type(int: IntTy) -> &'static str {
  match int {
    IntTy::I8 => "int8_t",
    IntTy::I16 => "int16_t",
    IntTy::I32 => "int32_t",
    IntTy::I64 => "int64_t",
    IntTy::Isize => "intptr_t",
    IntTy::U8 => "uint8_t",
    IntTy::U16 => "uint16_t",
    IntTy::U32 => "uint32_t",
    IntTy::U64 => "uint64_t",
    IntTy::Usize => "size_t",
  }
}

fn operand(operand: &Operand) -> String {
  match operand {
    Operand::Param(index) => format!("p{index}"),
    Operand::Const(Const::Unit) => "0".to_string(),
    Operand::Const(Const::Bool(value)) => value.to_string(),
    Operand::Const(Const::Char(value)) => format!("((uint32_t)0x{:X}u)", u32::from(*value)),
    // Literals are range-checked by the type checker, so the cast never changes the value.
    Operand::Const(Const::Int(value, int)) => format!("(({}){value}ull)", int_c_type(*int)),
    Operand::Const(Const::Float(text, float)) => {
      let text = if text.contains(['.', 'e']) { text.clone() } else { format!("{text}.0") };

      match float {
        FloatTy::F32 => format!("{text}f"),
        FloatTy::F64 => text,
      }
    }
    Operand::Const(Const::Str(value)) => {
      format!("sag_string_from_static({}, {})", c_string_literal(value.as_bytes()), value.len())
    }
  }
}

/// A C string literal holding exactly `bytes`. Anything outside printable ASCII becomes a
/// three-digit octal escape, which cannot merge with the following character. `?` is escaped to
/// avoid trigraphs.
fn c_string_literal(bytes: &[u8]) -> String {
  let mut out = String::from("\"");

  for &byte in bytes {
    match byte {
      b'"' => out.push_str("\\\""),
      b'\\' => out.push_str("\\\\"),
      b'?' => out.push_str("\\?"),
      b' '..=b'~' => out.push(char::from(byte)),
      _ => out.push_str(&format!("\\{byte:03o}")),
    }
  }

  out.push('"');

  out
}

#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn escapes_c_string_literals() {
    assert_eq!(c_string_literal(b"a\"b\\c?"), r#""a\"b\\c\?""#);
    assert_eq!(c_string_literal("ñ\n1".as_bytes()), r#""\303\261\0121""#);
  }

  #[test]
  fn formats_constants() {
    assert_eq!(operand(&Operand::Const(Const::Int(255, IntTy::U8))), "((uint8_t)255ull)");
    assert_eq!(operand(&Operand::Const(Const::Float("7".to_string(), FloatTy::F32))), "7.0f");
    assert_eq!(operand(&Operand::Const(Const::Float("1e10".to_string(), FloatTy::F64))), "1e10");
    assert_eq!(operand(&Operand::Const(Const::Char('A'))), "((uint32_t)0x41u)");
    assert_eq!(operand(&Operand::Const(Const::Str("hi".to_string()))), "sag_string_from_static(\"hi\", 2)");
  }

  #[test]
  fn generates_a_hello_world() {
    let program = Program {
      functions: vec![Function {
        name: "main".to_string(),
        params: Vec::new(),
        ret: Type::Unit,
        body: vec![
          Inst::Line(1),
          Inst::Call { callee: Callee::Builtin(Builtin::Println), args: vec![Operand::Const(Const::Str("hola".to_string()))] },
        ],
      }],
      entry: FnId(0),
      source_path: "main.sag".to_string(),
    };
    let expected = "\
/* Generated by sag. Do not edit. */
#include \"sagitario_runtime.h\"

static void sag_fn_0(void);

static void sag_fn_0(void) {
#line 1 \"main.sag\"
  sag_println(sag_string_from_static(\"hola\", 4));
}

int main(int argc, char **argv) {
  sag_rt_init(argc, argv);
  sag_fn_0();
  return sag_rt_finish();
}
";

    assert_eq!(generate(&program), expected);
  }
}
