//! The foreign function interface (docs/spec/10-ffi.md): C types, raw pointers, `unsafe`,
//! `extern` declarations, exported functions and `@repr(C)` structs.

use std::collections::HashMap;

use sagitario_ast::{Expr, ExprKind, FnDecl, Ident, TypeExpr, UnaryOp};
use sagitario_diagnostics::{Diagnostic, codes};
use sagitario_resolve::{CType, ExternId, TypeItem};
use sagitario_span::Span;

use crate::{BuiltinMethod, Checker, FloatTy, FnSig, IntTy, PlaceUse, Type};

/// The Sagitario type of a C type on the target. The MVP compiles for the machine running the
/// compiler, so its C ABI decides: `long` is 32 bits on Windows, and `char` is unsigned on Linux
/// for ARM.
pub fn c_type(ty: CType) -> Type {
  let long_is_32 = cfg!(windows);
  let char_is_unsigned = cfg!(all(target_os = "linux", any(target_arch = "aarch64", target_arch = "arm")));

  match ty {
    CType::Char if char_is_unsigned => Type::Int(IntTy::U8),
    CType::Char | CType::SChar => Type::Int(IntTy::I8),
    CType::UChar => Type::Int(IntTy::U8),
    CType::Short => Type::Int(IntTy::I16),
    CType::UShort => Type::Int(IntTy::U16),
    CType::Int => Type::Int(IntTy::I32),
    CType::UInt => Type::Int(IntTy::U32),
    CType::Long if long_is_32 => Type::Int(IntTy::I32),
    CType::ULong if long_is_32 => Type::Int(IntTy::U32),
    CType::Long | CType::LongLong => Type::Int(IntTy::I64),
    CType::ULong | CType::ULongLong => Type::Int(IntTy::U64),
    CType::Float => Type::Float(FloatTy::F32),
    CType::Double => Type::Float(FloatTy::F64),
    CType::Void => Type::CVoid,
  }
}

/// `*const c_char`, the type of C strings.
pub fn c_string_ptr() -> Type {
  Type::Ptr { mutable: false, pointee: Box::new(c_type(CType::Char)) }
}

/// Words C reserves, which cannot be C symbols: keywords, and names the C files generated by
/// `sag` define (`bool`, `true`, `false`, `NULL`, `main`).
const C_RESERVED: &[&str] = &[
  "auto", "break", "case", "char", "const", "continue", "default", "do", "double", "else", "enum", "extern", "float", "for", "goto", "if", "inline",
  "int", "long", "register", "restrict", "return", "short", "signed", "sizeof", "static", "struct", "switch", "typedef", "union", "unsigned", "void",
  "volatile", "while", "bool", "true", "false", "NULL", "main", "offsetof",
];

/// Why a symbol cannot be used in C, or `None` if it can.
fn symbol_problem(symbol: &str) -> Option<String> {
  let mut chars = symbol.chars();
  let valid = chars.next().is_some_and(|first| first.is_ascii_alphabetic() || first == '_') && chars.all(|c| c.is_ascii_alphanumeric() || c == '_');

  if !valid {
    return Some(format!("`{symbol}` is not a C identifier (ASCII letters, digits and `_`, not starting with a digit)"));
  }

  if C_RESERVED.contains(&symbol)
    || symbol.starts_with("__")
    || (symbol.starts_with('_') && symbol.chars().nth(1).is_some_and(|c| c.is_ascii_uppercase()))
  {
    return Some(format!("`{symbol}` is reserved in C"));
  }

  if symbol.starts_with("sag_") || symbol.starts_with("SAG_") || symbol.starts_with("_Z") || symbol.ends_with("_t") {
    return Some(format!("`{symbol}` is reserved: names starting with `sag_` belong to the Sagitario runtime, and names ending in `_t` to C types"));
  }

  None
}

/// A C symbol the program declares or defines.
enum Symbol {
  Imported(Span, FnSig),
  Exported(Span),
}

impl Checker<'_> {
  /// `*const T` or `*mut T`; the pointee is checked once all types are known.
  pub(crate) fn pointer_type(&mut self, mutable: bool, pointee: &TypeExpr) -> Type {
    let pointee_ty = self.type_expr_at(pointee, true);

    self.pointees.push((pointee.span, pointee_ty.clone()));

    Type::Ptr { mutable, pointee: Box::new(pointee_ty) }
  }

  /// A `c_void` outside a pointer.
  pub(crate) fn bare_c_void(&mut self, span: Span) -> Type {
    self.diagnostics.push(
      Diagnostic::error(codes::NOT_FFI_SAFE, span, "`c_void` can only be used behind a pointer").with_help("write `*mut c_void` or `*const c_void`"),
    );

    Type::Error
  }

  /// Pointers cannot point to values with ARC references: C would copy or free them unseen.
  pub(crate) fn check_pointees(&mut self) {
    for (span, ty) in std::mem::take(&mut self.pointees) {
      if self.is_managed(&ty, &mut Vec::new()) {
        self.diagnostics.push(
          Diagnostic::error(codes::NOT_FFI_SAFE, span, format!("a pointer cannot point to `{ty}`, which holds reference-counted values"))
            .with_note("pass strings to C as `CString` and read them back with `string_from_c`"),
        );
      }
    }
  }

  /// Whether values of `ty` hold `String`s or other ARC references.
  pub(crate) fn is_managed(&self, ty: &Type, visited: &mut Vec<TypeItem>) -> bool {
    match ty {
      Type::String | Type::StringBuilder | Type::CString | Type::Class(_) | Type::List(_) => true,
      Type::Array(elem, _) | Type::Option(elem) => self.is_managed(elem, visited),
      Type::Result(value, error) => self.is_managed(value, visited) || self.is_managed(error, visited),
      Type::Struct(inner) => {
        if visited.contains(&TypeItem::Struct(inner.id)) {
          return false;
        }

        visited.push(TypeItem::Struct(inner.id));

        let fields: Vec<Type> =
          self.typed.struct_def(inner.id).map(|def| def.fields.iter().map(|field| field.ty.clone()).collect()).unwrap_or_default();

        fields.iter().any(|field| self.is_managed(field, visited))
      }
      Type::Enum(inner) => {
        if visited.contains(&TypeItem::Enum(inner.id)) {
          return false;
        }

        visited.push(TypeItem::Enum(inner.id));

        let parts: Vec<Type> = self.typed.variants(ty).unwrap_or_default().iter().flat_map(|variant| variant.field_types()).collect();

        parts.iter().any(|part| self.is_managed(part, visited))
      }
      _ => false,
    }
  }

  /// Whether C can receive or return values of `ty`: numbers, `bool`, pointers and `@repr(C)`
  /// structs.
  fn ffi_safe(&self, ty: &Type) -> bool {
    match ty {
      Type::Int(_) | Type::Float(_) | Type::Bool | Type::Ptr { .. } | Type::Error | Type::Never => true,
      Type::Struct(inner) => self.resolution.struct_decl(self.package, inner.id).is_some_and(|decl| decl.repr_c),
      _ => false,
    }
  }

  fn not_ffi_safe(&mut self, span: Span, ty: &Type, context: &str) {
    let help = match ty {
      Type::String => "pass a `CString` with `as_ptr()`, a `*const c_char`",
      Type::Char => "pass the code point as `u32`",
      Type::Struct(_) => "mark the struct `@repr(C)`",
      _ => "C takes numbers, `bool`, raw pointers and `@repr(C)` structs",
    };

    self
      .diagnostics
      .push(Diagnostic::error(codes::NOT_FFI_SAFE, span, format!("{context} has type `{ty}`, which C cannot represent")).with_help(help));
  }

  /// The parameters and result of a function C calls or is called through.
  fn check_ffi_signature(&mut self, sig: &FnSig, params: &[&TypeExpr], ret: Option<&TypeExpr>) {
    for (ty, expr) in sig.params.iter().zip(params) {
      if !self.ffi_safe(ty) {
        self.not_ffi_safe(expr.span, ty, "this parameter");
      }
    }

    if let Some(expr) = ret
      && sig.ret != Type::Unit
      && !self.ffi_safe(&sig.ret)
    {
      self.not_ffi_safe(expr.span, &sig.ret, "the result");
    }
  }

  /// The signatures of the C functions in `extern` blocks.
  pub(crate) fn extern_sigs(&mut self) {
    for (_, decl) in self.resolution.extern_decls(self.package) {
      let params: Vec<Type> = decl.params.iter().map(|param| self.type_expr(&param.ty)).collect();
      let ret = decl.return_type.as_ref().map_or(Type::Unit, |ty| self.type_expr(ty));
      let sig = FnSig { receiver: None, params, ret };
      let param_exprs: Vec<&TypeExpr> = decl.params.iter().map(|param| &param.ty).collect();

      self.check_ffi_signature(&sig, &param_exprs, decl.return_type.as_ref());
      self.typed.extern_sigs.push(sig);
    }
  }

  /// `extern "C" fn`: a function with the C ABI, which C can call.
  pub(crate) fn check_exported(&mut self, decl: &FnDecl, sig: &FnSig) {
    let params: Vec<&TypeExpr> = decl.params.iter().map(|param| &param.ty).collect();

    self.check_ffi_signature(sig, &params, decl.return_type.as_ref());
  }

  /// The fields of `@repr(C)` structs, which C reads with its own layout.
  pub(crate) fn check_repr_c_structs(&mut self) {
    for index in 0..self.resolution.structs.len() {
      let id = sagitario_resolve::StructId(index as u32);
      let Some(decl) = self.resolution.struct_decl(self.package, id).filter(|decl| decl.repr_c) else { continue };
      let fields: Vec<Type> = self.typed.struct_def(id).map(|def| def.fields.iter().map(|field| field.ty.clone()).collect()).unwrap_or_default();

      for (field, ty) in decl.fields.iter().zip(fields) {
        if !self.ffi_safe(&ty) {
          self.not_ffi_safe(field.ty.span, &ty, &format!("the field `{}` of the `@repr(C)` struct `{}`", field.name.name, decl.name.name));
        }
      }
    }
  }

  /// Checks the C symbols: valid identifiers, not reserved, each declared or defined once (a
  /// C function may be declared in several `extern` blocks with the same signature).
  pub(crate) fn check_symbols(&mut self) {
    let mut symbols: HashMap<String, Symbol> = HashMap::new();
    let mut found: Vec<(String, Span, Option<FnSig>)> = Vec::new();

    for (id, decl) in self.resolution.extern_decls(self.package) {
      let sig = self.typed.extern_sig(id).cloned();

      found.push((decl.name.name.clone(), decl.name.span, sig));
    }

    for (_, decl) in self.resolution.fn_decls(self.package) {
      if decl.extern_c {
        let (symbol, span) = decl.export.as_ref().map_or((decl.name.name.clone(), decl.name.span), |export| (export.symbol.clone(), export.span));

        found.push((symbol, span, None));
      }
    }

    for (symbol, span, sig) in found {
      if let Some(problem) = symbol_problem(&symbol) {
        self.diagnostics.push(
          Diagnostic::error(codes::INVALID_SYMBOL, span, format!("cannot use `{symbol}` as a C symbol"))
            .with_note(problem)
            .with_help("rename the function, or choose the exported name with `@export(\"name\")`"),
        );

        continue;
      }

      let clash = match (symbols.get(&symbol), &sig) {
        (None, _) => None,
        (Some(Symbol::Imported(_, previous)), Some(sig)) if previous == sig => continue,
        (Some(Symbol::Imported(previous, _)), Some(_)) => Some((*previous, "declared again here with a different signature")),
        (Some(Symbol::Imported(previous, _) | Symbol::Exported(previous)), _) => Some((*previous, "first used here")),
      };

      if let Some((previous, message)) = clash {
        self.diagnostics.push(
          Diagnostic::error(codes::INVALID_SYMBOL, span, format!("the C symbol `{symbol}` is already used"))
            .with_label(previous, "first used here")
            .with_note(format!("each C symbol is defined once; a C function can be declared again only with the same signature ({message})")),
        );

        continue;
      }

      let entry = match sig {
        Some(sig) => Symbol::Imported(span, sig),
        None => Symbol::Exported(span),
      };

      symbols.insert(symbol, entry);
    }
  }

  /// Marks the innermost `unsafe` block as needed, or reports that one is missing.
  pub(crate) fn require_unsafe(&mut self, span: Span, what: &str) {
    if let Some(used) = self.unsafe_blocks.last_mut() {
      *used = true;

      return;
    }

    self.diagnostics.push(
      Diagnostic::error(codes::UNSAFE_REQUIRED, span, format!("{what} is unsafe and needs an `unsafe` block"))
        .with_help("wrap it in `unsafe { ... }` after checking that the operation is valid"),
    );
  }

  /// `unsafe { ... }`
  pub(crate) fn unsafe_block(&mut self, expr: &Expr, block: &sagitario_ast::Block, expected: Option<&Type>) -> Type {
    self.unsafe_blocks.push(false);

    let ty = self.block(block, expected);

    if self.unsafe_blocks.pop() == Some(false) {
      let keyword = Span::new(expr.span.file, expr.span.start, expr.span.start.saturating_add(6));

      self.diagnostics.push(
        Diagnostic::warning(codes::UNUSED_UNSAFE, keyword, "unnecessary `unsafe` block")
          .with_note("it contains no call to C, pointer dereference or pointer offset"),
      );
    }

    ty
  }

  /// `*pointer`
  pub(crate) fn deref(&mut self, expr: &Expr, operand: &Expr) -> Type {
    let ty = self.expr(operand, None);

    match ty {
      Type::Ptr { ref pointee, .. } if **pointee == Type::CVoid => {
        self.error(codes::INVALID_OPERAND, expr.span, format!("cannot dereference a `{ty}`; cast it to a pointer to a known type first"));

        Type::Error
      }
      Type::Ptr { pointee, .. } => {
        self.require_unsafe(expr.span, "dereferencing a raw pointer");

        *pointee
      }
      Type::Error | Type::Never => Type::Error,
      other => {
        self.error(codes::INVALID_OPERAND, expr.span, format!("cannot dereference a value of type `{other}`; only raw pointers can be"));

        Type::Error
      }
    }
  }

  /// The pointer a place is reached through (`*p`, `(*p).x`), if any.
  pub(crate) fn deref_pointer<'e>(&self, place: &'e Expr) -> Option<&'e Expr> {
    match &place.kind {
      ExprKind::Unary { op: UnaryOp::Deref, operand } => Some(operand),
      ExprKind::Field { base, .. } | ExprKind::Index { base, .. } => self.deref_pointer(base),
      _ => None,
    }
  }

  /// Writing through a pointer needs a `*mut` one.
  pub(crate) fn check_pointer_write(&mut self, place: &Expr, pointer: &Expr) {
    if let Some(Type::Ptr { mutable: false, .. }) = self.typed.expr_types.get(&pointer.id) {
      self.diagnostics.push(
        Diagnostic::error(codes::IMMUTABLE_PLACE, place.span, "cannot modify a value through a `*const` pointer")
          .with_help("use a `*mut` pointer, for example with `as *mut T`"),
      );
    }
  }

  /// Methods of raw pointers, `CString` and the `as_ptr`/`as_mut_ptr` of arrays.
  pub(crate) fn ffi_method(&mut self, expr: &Expr, receiver: &Expr, receiver_ty: &Type, method: &Ident, args: &[Expr]) -> Option<Type> {
    let runtime = |function: &'static str| BuiltinMethod::Runtime { function, located: false };
    let (builtin, params, ret) = match (receiver_ty, method.name.as_str()) {
      (Type::Ptr { .. }, "is_null") => (runtime("SAG_PTR_IS_NULL"), Vec::new(), Type::Bool),
      (Type::Ptr { pointee, .. }, "add") => {
        if **pointee == Type::CVoid {
          self.error(codes::INVALID_OPERAND, method.span, format!("cannot offset a `{receiver_ty}`; its pointee has no size"));
        } else {
          self.require_unsafe(expr.span, "offsetting a raw pointer");
        }

        (runtime("SAG_PTR_ADD"), vec![Type::Int(IntTy::Usize)], receiver_ty.clone())
      }
      (Type::CString, "as_ptr") => (runtime("sag_cstring_ptr"), Vec::new(), c_string_ptr()),
      (Type::Array(elem, _), "as_ptr" | "as_mut_ptr") => {
        let mutable = method.name == "as_mut_ptr";

        if self.is_managed(elem, &mut Vec::new()) {
          self.diagnostics.push(Diagnostic::error(
            codes::NOT_FFI_SAFE,
            method.span,
            format!("a pointer cannot point to `{elem}`, which holds reference-counted values"),
          ));
        }

        if mutable {
          self.check_mutable_place(receiver, PlaceUse::Receiver("as_mut_ptr"));
        }

        let function = if mutable { "SAG_ARRAY_MUT_PTR" } else { "SAG_ARRAY_PTR" };

        (runtime(function), Vec::new(), Type::Ptr { mutable, pointee: elem.clone() })
      }
      (Type::Ptr { .. } | Type::CString, name) => {
        let available = if matches!(receiver_ty, Type::CString) { "`as_ptr`" } else { "`is_null` and `add`" };

        self.diagnostics.push(
          Diagnostic::error(codes::UNKNOWN_MEMBER, method.span, format!("no method `{name}` on type `{receiver_ty}`"))
            .with_note(format!("its methods are {available}")),
        );
        self.unchecked_args(args);

        return Some(Type::Error);
      }
      _ => return None,
    };

    self.args(expr.span, "method", &params, args);
    self.typed.builtin_methods.insert(expr.id, builtin);

    Some(ret)
  }

  /// The signature of a C function of an `extern` block.
  pub(crate) fn extern_call_sig(&mut self, callee: &Expr, id: ExternId) -> Option<FnSig> {
    let name = self.resolution.extern_decl(self.package, id).map_or_else(String::new, |decl| decl.name.name.clone());

    self.require_unsafe(callee.span, &format!("calling the C function `{name}`"));
    self.typed.extern_sig(id).cloned()
  }
}

#[cfg(test)]
mod tests {
  use super::symbol_problem;

  #[test]
  fn validates_c_symbols() {
    assert_eq!(symbol_problem("puts"), None);
    assert_eq!(symbol_problem("_private"), None);
    assert!(symbol_problem("ñandú").is_some());
    assert!(symbol_problem("int").is_some());
    assert!(symbol_problem("__x").is_some());
    assert!(symbol_problem("_X").is_some());
    assert!(symbol_problem("sag_fn_1").is_some());
    assert!(symbol_problem("size_t").is_some());
    assert!(symbol_problem("main").is_some());
  }
}
